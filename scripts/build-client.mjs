#!/usr/bin/env node
/**
 * Client bundle build: concatenate every fragment in `client/src` (lexicographic
 * order) into the `__ModuleLoader__.load({ id, factory })` wrapper that the Host
 * serves, then syntax-check the result.
 *
 * Fragments share one function scope, so `90-apply.js` can call any function a
 * lower-numbered fragment declares. Fragments must not use `import`/`export`.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'

const run = promisify(execFile)
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const sourceDir = join(root, 'client', 'src')
const outputFile = join(root, 'client', 'client.js')
const PACKAGE_ID = 'dsh-flutter-workbench'

const HEADER = `/**
 * dsh-flutter-workbench — Client half.
 * GENERATED by scripts/build-client.mjs from client/src/*.js — do not edit.
 *
 * Format: window.__ModuleLoader__.load({ id, factory }). \`factory(require)\` gets
 * the browser module table; React is the only module required. The factory must
 * not touch \`exports\`/\`module\`; it returns the plugin exports object instead.
 *
 * Surfaces: the \`main\` keyed panel (key \`flutter-workbench\`) and one
 * \`sidebar.panellist\` icon.
 */
window.__ModuleLoader__.load({
  id: '${PACKAGE_ID}',
  factory: (require) => {
    const React = require('react')
`

const FOOTER = `  },
})
`

async function main() {
  const files = (await readdir(sourceDir)).filter((name) => name.endsWith('.js')).sort()
  if (files.length === 0) {
    process.stderr.write(`build-client: no fragments in ${sourceDir}\n`)
    process.exit(1)
  }

  const parts = [HEADER]
  for (const name of files) {
    const text = await readFile(join(sourceDir, name), 'utf8')
    if (/\b(?:import|export)\s/.test(text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, ''))) {
      process.stderr.write(`build-client: ${name} uses import/export; fragments must be plain statements\n`)
      process.exit(1)
    }
    parts.push(`    /* ==== ${name} ==== */\n${text.trimEnd()}\n`)
  }
  parts.push(FOOTER)

  const bundle = parts.join('\n')
  await writeFile(outputFile, bundle, 'utf8')

  try {
    await run(process.execPath, ['--check', outputFile])
  } catch (error) {
    process.stderr.write(`build-client: syntax error in the generated bundle\n${error.stdout ?? ''}${error.stderr ?? ''}\n`)
    process.exit(1)
  }

  const bytes = Buffer.byteLength(bundle)
  process.stdout.write(`build-client: ${files.length} fragments → client/client.js (${bytes} bytes)\n`)
}

await main()